// 二分查找：返回码点的 Grapheme_Cluster_Break 类别，缺省 Gb::Any。
constexpr Gb grapheme_class(std::uint32_t cp) noexcept {
    std::size_t lo = 0;
    std::size_t hi = kGbRanges.size();
    while (lo < hi) {
        const std::size_t mid = lo + (hi - lo) / 2;
        const GbRange& r = kGbRanges[mid];
        if (cp < r.first) {
            hi = mid;
        } else if (cp > r.last) {
            lo = mid + 1;
        } else {
            return r.value;
        }
    }
    return Gb::Any;
}

